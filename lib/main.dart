/// Runs a non-critical start-up step. A failing or hanging step (notification channel, history
/// store...) must never leave the user on a blank screen, so it is bounded and its error swallowed.
Future<void> _bestEffort(String name, Future<void> Function() step) async {
  try {
    await step().timeout(const Duration(seconds: 5));
  } catch (e) {
    debugPrint('[startup] $name failed: ${e.runtimeType}');
  }
}

Future<void> main() async {
  WidgetsFlutterBinding.ensureInitialized();

  // 0. Initialize SharedPreferences for theme system
  final prefs = await SharedPreferences.getInstance();
  ThemeStorage.prefs = prefs;

  // 1. Resolve backend URL (emulator vs real device)
  await AppConfig.initialize();

  // 2. Initialize AES-256 encryption (generates/loads key from Keystore)
  // If this fails the app still starts, but nothing can be saved encrypted (and nothing is saved in plaintext).
  await _bestEffort('encryption', EncryptionService.initialize);

  // 3. Initialize notification service (must be called before any notifications)
  await _bestEffort('notifications', NotificationService.initialize);

  // 4. Initialize scan history store (forensics/audit log)
  await _bestEffort('scan history', ScanHistoryStore.initialize);

  // 5. Run device security checks (root, Magisk, Xposed, Frida, emulator)
  final secReport = await SecurityService.runChecks();
  if (secReport.riskLevel == 'danger') {
    // Hard-block: rooted / Magisk / Xposed / Frida-instrumented device
    runApp(SecurityBlockApp(reasons: secReport.riskReasons));
    return;
  }

  // 6. SIM-integrity check — non-blocking. The alertable verdict is
  //    consumed by the SecureShield app's router so the alert can sit on
  //    top of the normal navigation stack instead of blocking startup.
  SimIntegrityReport? simReport;
  try {
    simReport = await SimIntegrityService.instance.check();
  } catch (_) {
    simReport = null;
  }

  runApp(ProviderScope(
    child: SecureShieldApp(
      securityReport: secReport,
      simReport: simReport,
    ),
  ));
}

class SecureShieldApp extends ConsumerStatefulWidget {
  final SecurityReport securityReport;
  final SimIntegrityReport? simReport;
  const SecureShieldApp({
    super.key,
    required this.securityReport,
    this.simReport,
  });

  @override
  ConsumerState<SecureShieldApp> createState() => _SecureShieldAppState();
}

class _SecureShieldAppState extends ConsumerState<SecureShieldApp> {
  @override
  void initState() {
    super.initState();
    // Show the SIM-swap alert on top of the normal navigation stack once
    // the first frame is up.
    final sim = widget.simReport;
    if (sim != null && sim.isAlertable) {
      WidgetsBinding.instance.addPostFrameCallback((_) {
        final navKey = ref.read(routerProvider).routerDelegate.navigatorKey;
        final state = navKey.currentState;
        if (state != null) {
          state.push(MaterialPageRoute(
            fullscreenDialog: true,
            builder: (_) => SimAlertScreen(report: sim),
          ));
        }
      });
    }
  }

  @override
  Widget build(BuildContext context) {
    final router      = ref.watch(routerProvider);
    final themeState  = ref.watch(themeProvider);
    final themeType   = themeState.themeType;
    final themeMode   = themeState.themeMode;
    final locale      = ref.watch(localeProvider);

    return MaterialApp.router(
      title: 'SecureShield AI',
      debugShowCheckedModeBanner: false,
      // Fallbacks for MaterialApp's light/dark slots — actual rendering uses
      // the `builder:` below which passes the user-selected theme.
      theme:      AppTheme.getTheme(AppThemeType.corporateLight),
      darkTheme:  AppTheme.getTheme(AppThemeType.defenderBlue),
      themeMode:  themeMode,
      locale: locale,
      localizationsDelegates: const [
        AppLocalizations.delegate,
        GlobalMaterialLocalizations.delegate,
        GlobalWidgetsLocalizations.delegate,
        GlobalCupertinoLocalizations.delegate,
      ],
      supportedLocales: AppLocalizations.supportedLocales,
      routerConfig: router,
      builder: (context, child) {
        return Theme(
          data: AppTheme.getTheme(themeType),
          child: child ?? const SizedBox.shrink(),
        );
      },
    );
  }
}

/// Shown when device fails critical security check (e.g. rooted)
class SecurityBlockApp extends StatelessWidget {
  final List<String> reasons;
  const SecurityBlockApp({super.key, required this.reasons});

  @override
  Widget build(BuildContext context) {
    return MaterialApp(
      debugShowCheckedModeBanner: false,
      theme: AppTheme.getTheme(AppThemeType.defenderBlue), // Post-migration default
      home: Scaffold(
        backgroundColor: const Color(0xFF0A0E27),
        body: SafeArea(
          child: Center(
            child: Padding(
              padding: const EdgeInsets.all(32),
              child: Column(
                mainAxisAlignment: MainAxisAlignment.center,
                children: [
                  const Icon(Icons.gpp_bad, size: 80, color: Color(0xFFFF1744)),
                  const SizedBox(height: 24),
                  const Text(
                    'Security Risk Detected',
                    style: TextStyle(
                      color: Colors.white,
                      fontSize: 24,
                      fontWeight: FontWeight.bold,
                    ),
                    textAlign: TextAlign.center,
                  ),
                  const SizedBox(height: 16),
                  const Text(
                    'SecureShield AI cannot run on a compromised device.\nThis protects your sensitive security data.',
                    style: TextStyle(color: Color(0xFF90A4AE), fontSize: 14),
                    textAlign: TextAlign.center,
                  ),
                  const SizedBox(height: 24),
                  ...reasons.map((r) => Padding(
                    padding: const EdgeInsets.symmetric(vertical: 4),
                    child: Row(
                      mainAxisAlignment: MainAxisAlignment.center,
                      children: [
                        const Icon(Icons.warning_amber, color: Color(0xFFFF9100), size: 16),
                        const SizedBox(width: 8),
                        Text(r, style: const TextStyle(color: Color(0xFFFF9100), fontSize: 13)),
                      ],
                    ),
                  )),
                ],
              ),
            ),
          ),
        ),
      ),
    );
  }
}
