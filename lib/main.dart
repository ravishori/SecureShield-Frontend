Future<void> main() async {
  WidgetsFlutterBinding.ensureInitialized();

  // 0. Initialize SharedPreferences for theme system
  final prefs = await SharedPreferences.getInstance();
  ThemeStorage.prefs = prefs;

  // 1. Resolve backend URL (emulator vs real device)
  await AppConfig.initialize();

  // 2. Initialize AES-256 encryption (generates/loads key from Keystore)
  await EncryptionService.initialize();

  // 3. Initialize notification service (must be called before any notifications)
  await NotificationService.initialize();

  // 4. Initialize scan history store (forensics/audit log)
  await ScanHistoryStore.initialize();

  // 5. Run device security checks (root, emulator, screen recording)
  final secReport = await SecurityService.runChecks();
  if (secReport.riskLevel == 'danger') {
    // Rooted device — show blocking warning
    runApp(SecurityBlockApp(reasons: secReport.riskReasons));
    return;
  }

  runApp(ProviderScope(
    child: SecureShieldApp(securityReport: secReport),
  ));
}

class SecureShieldApp extends ConsumerWidget {
  final SecurityReport securityReport;
  const SecureShieldApp({super.key, required this.securityReport});

  @override
  Widget build(BuildContext context, WidgetRef ref) {
    final router      = ref.watch(routerProvider);
    final themeState  = ref.watch(themeProvider); // New: Get full theme state
    final themeType   = themeState.themeType;      // New: Extract theme type
    final themeMode   = themeState.themeMode;      // New: Extract theme mode
    final locale      = ref.watch(localeProvider);

    return MaterialApp.router(
      title: 'SecureShield AI',
      debugShowCheckedModeBanner: false,
      // NEW: Dynamic theme based on user selection
      theme:      AppTheme.getTheme(AppThemeType.light),   // Light fallback
      darkTheme:  AppTheme.getTheme(AppThemeType.dark),    // Dark fallback
      themeMode:  themeMode,                                // User's choice
      // ── Localisation ──────────────────────────────────────────────────────
      locale: locale,
      localizationsDelegates: const [
        AppLocalizations.delegate,
        GlobalMaterialLocalizations.delegate,
        GlobalWidgetsLocalizations.delegate,
        GlobalCupertinoLocalizations.delegate,
      ],
      supportedLocales: AppLocalizations.supportedLocales,
      routerConfig: router,
      // NEW: Builder to apply the selected theme dynamically
      builder: (context, child) {
        return Theme(
          data: AppTheme.getTheme(themeType),
          child: child ?? const SizedBox.shrink(),
        );
      },
    );
  }
}

